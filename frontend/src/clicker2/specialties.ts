export const SPECIALTY_IDS = new Set(SPECIALTIES.map((s) => s.id));

export function getSpecialtyDef(id: number): SpecialtyDef | undefined {
  return SPECIALTIES.find((s) => s.id === id);
}

export function specialtiesForDenizen(denizenId: string): SpecialtyDef[] {
  return SPECIALTIES.filter((s) => s.denizenId === denizenId);
}

/** Shop grid: lowest price first (pond production mixed with other evolutions). */
export function compareVisibleSpecialtyShopOrder(
  a: SpecialtyDef,
  b: SpecialtyDef,
): number {
  if (a.price !== b.price) return a.price - b.price;
  return a.id - b.id;
}

/** Zero-based tier index (0–14) within the denizen's fifteen specialties. */
export function specialtyTierIndex(def: SpecialtyDef): number {
  const idx = specialtiesForDenizen(def.denizenId).findIndex((s) => s.id === def.id);
  return idx >= 0 ? idx : 0;
}
