export type SpecialtyEffect =
  | { type: "double_click_and_denizen"; denizenId: string }
  | { type: "double_denizen"; denizenId: string }
  | { type: "concentric_rings" }
  | { type: "concentric_rings_mult"; factor: number }
  | { type: "production_percent"; percent: number };

export type SpecialtyDef = {
  id: number;
  name: string;
  denizenId: string;
  /** Owned count of `denizenId` required when `unlockAllTimeEnergy` is unset. */
  unlockOwned: number;
  /** Pond production tiers: unlock when all-time energy earned reaches this value. */
  unlockAllTimeEnergy?: number;
  price: number;
  effect: SpecialtyEffect;
  effectText: string;
  ecologyNote: string;
};

function rippleClick(
  id: number,
  name: string,
  unlock: number,
  ecologyNote: string,
): SpecialtyDef {
  return {
    id,
    name,
    denizenId: "ripples",
    unlockOwned: unlock,
    price: specialtyCatalogPrice(id),
    effect: { type: "double_click_and_denizen", denizenId: "ripples" },
    effectText: "Mouse click and Ripples are twice as efficient",
    ecologyNote,
  };
}

function doubleDenizen(
  id: number,
  name: string,
  denizenId: string,
  unlock: number,
  price: number,
  ecologyNote: string,
): SpecialtyDef {
  const def = getDenizenDef(denizenId);
  const effectText = def
    ? denizenDoubleEfficiencyEffectText(def)
    : "Denizens are twice as efficient";
  return {
    id,
    name,
    denizenId,
    unlockOwned: unlock,
    price,
    effect: { type: "double_denizen", denizenId },
    effectText,
    ecologyNote,
  };
}

/** Owned denizen count required per specialty tier index (0–14) within a denizen chain. */
export const DENIZEN_SPECIALTY_UNLOCK_TIER = [
  1, 5, 25, 50, 100, 150, 200, 250, 300, 350, 400, 450, 500, 550, 600,
] as const;

const UNLOCK_TIER = DENIZEN_SPECIALTY_UNLOCK_TIER;

/** Pond-wide production specialties (not tied to a denizen owned count). */
export const POND_SPECIALTY_DENIZEN_ID = "pond" as const;

/** Canonical evolution tier multipliers (price = round(baseCost × mult)). */
export const DENIZEN_SPECIALTY_COST_MULT = DENIZEN_EVOLUTION_TIER_MULT;

export function specialtyPriceForDenizenTier(
  baseCost: number,
  tierIndex: number,
): number {
  const mult =
    DENIZEN_EVOLUTION_TIER_MULT[tierIndex] ??
    DENIZEN_EVOLUTION_TIER_MULT[DENIZEN_EVOLUTION_TIER_MULT.length - 1]!;
  return Math.round(baseCost * mult);
}

