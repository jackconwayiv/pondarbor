/** Tiers 0–2: +1%; tiers 3–17: +2% each. */
function pondProductionPercentForTierIndex(tierIndex: number): number {
  return tierIndex < 3 ? 1 : 2;
}

function productionPercentSpecialty(
  id: number,
  name: string,
  denizenId: string,
  tierIndex: number,
  price: number,
  ecologyNote: string,
  unlock: { unlockOwned: number } | { unlockAllTimeEnergy: number },
): SpecialtyDef {
  const percent = pondProductionPercentForTierIndex(tierIndex);
  return {
    id,
    name,
    denizenId,
    unlockOwned: "unlockOwned" in unlock ? unlock.unlockOwned : 0,
    unlockAllTimeEnergy:
      "unlockAllTimeEnergy" in unlock ? unlock.unlockAllTimeEnergy : undefined,
    price,
    effect: { type: "production_percent", percent },
    effectText: `+${percent}% energy production multiplier`,
    ecologyNote,
  };
}

function buildPondProductionChain(
  ecologyNotes: readonly string[],
  names: readonly string[],
): SpecialtyDef[] {
  return POND_UNLOCK_ENERGY.map((unlockAllTimeEnergy, i) =>
    productionPercentSpecialty(
      POND_PRODUCTION_IDS[i]!,
      names[i] ?? `Production ${i + 1}`,
      POND_SPECIALTY_DENIZEN_ID,
      i,
      specialtyCatalogPrice(POND_PRODUCTION_IDS[i]!),
      ecologyNotes[i] ?? "",
      { unlockAllTimeEnergy },
    ),
  );
}

